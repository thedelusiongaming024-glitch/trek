async function run() {
  console.log('Updating FAQs in database with Bengali translations...');
  let updatedCount = 0;
  for (const [id, data] of Object.entries(bnUpdates)) {
    const res = await pool.query(
      `UPDATE faqs SET question_bn = $1, answer_bn = $2, updated_at = NOW() WHERE id = $3 RETURNING id`,
      [data.q_bn, data.a_bn, id]
    );
    if (res.rowCount && res.rowCount > 0) {
      updatedCount++;
      console.log(`Updated FAQ [${id}]`);
    } else {
      console.log(`FAQ [${id}] not found`);
    }
  }
  console.log(`Successfully updated ${updatedCount} FAQs with Bengali!`);
  process.exit(0);
}

run().catch((err) => {
  console.error('Error updating FAQs:', err);
  process.exit(1);
});
